"""
Tests for AI-Generated Note Saving.

Feature: When the AI assistant generates a note or summary in the chat,
         the user can save it with one click.  The saved note is persisted
         in the database with `is_ai_generated=True` and immediately appears
         in the left panel.

API endpoints to be implemented:
  POST /api/notes
    Request  (JSON): { "title": str, "content": str, "topic_id": int,
                       "is_ai_generated": bool,  "source_conversation_id": int? }
    Response (JSON): { "id": int, "title": str, "topic_id": int,
                       "is_ai_generated": true, "created_at": str }

  PATCH /api/notes/<id>   (optional – update title/content)
    Request  (JSON): { "title"?: str, "content"?: str }
    Response (JSON): updated note object

These tests will FAIL until the endpoint is implemented.
"""

import json
import pytest


# ---------------------------------------------------------------------------
# POST /api/notes  – create a note (human or AI)
# ---------------------------------------------------------------------------

class TestCreateNoteEndpoint:
    """POST /api/notes"""

    BASE_PAYLOAD = {
        "title": "My New Note",
        "content": "## Introduction\n\nSome markdown content here.",
        "is_ai_generated": False,
    }

    def test_requires_authentication(self, client, test_topic):
        payload = {**self.BASE_PAYLOAD, "topic_id": test_topic.id}
        response = client.post(
            "/api/notes",
            data=json.dumps(payload),
            content_type="application/json",
        )
        assert response.status_code in (401, 302)

    def test_creates_regular_note(self, logged_in_client, test_topic, db, app):
        payload = {**self.BASE_PAYLOAD, "topic_id": test_topic.id}
        response = logged_in_client.post(
            "/api/notes",
            data=json.dumps(payload),
            content_type="application/json",
        )
        assert response.status_code in (200, 201)
        data = json.loads(response.data)
        assert "id" in data
        assert data["is_ai_generated"] is False

        # Verify it was actually persisted
        from app.models import Note
        with app.app_context():
            note = db.session.get(Note, data["id"])
            assert note is not None
            assert note.title == "My New Note"
            assert note.is_ai_generated is False

    def test_creates_ai_generated_note(self, logged_in_client, test_topic, db, app):
        payload = {
            "title": "AI Summary",
            "content": "## Summary\n\nGenerated by the AI assistant.",
            "topic_id": test_topic.id,
            "is_ai_generated": True,
        }
        response = logged_in_client.post(
            "/api/notes",
            data=json.dumps(payload),
            content_type="application/json",
        )
        assert response.status_code in (200, 201)
        data = json.loads(response.data)
        assert data["is_ai_generated"] is True

        from app.models import Note
        with app.app_context():
            note = db.session.get(Note, data["id"])
            assert note is not None
            assert note.is_ai_generated is True

    def test_response_includes_all_required_fields(self, logged_in_client, test_topic):
        payload = {**self.BASE_PAYLOAD, "topic_id": test_topic.id, "is_ai_generated": True}
        response = logged_in_client.post(
            "/api/notes",
            data=json.dumps(payload),
            content_type="application/json",
        )
        data = json.loads(response.data)
        required = {"id", "title", "topic_id", "is_ai_generated", "created_at"}
        missing = required - set(data.keys())
        assert not missing, f"POST /api/notes response missing fields: {missing}"

    def test_requires_title(self, logged_in_client, test_topic):
        payload = {"content": "No title here", "topic_id": test_topic.id}
        response = logged_in_client.post(
            "/api/notes", data=json.dumps(payload), content_type="application/json"
        )
        assert response.status_code == 400

    def test_requires_content(self, logged_in_client, test_topic):
        payload = {"title": "No content", "topic_id": test_topic.id}
        response = logged_in_client.post(
            "/api/notes", data=json.dumps(payload), content_type="application/json"
        )
        assert response.status_code == 400

    def test_requires_topic_id(self, logged_in_client):
        payload = {"title": "No topic", "content": "Content"}
        response = logged_in_client.post(
            "/api/notes", data=json.dumps(payload), content_type="application/json"
        )
        assert response.status_code == 400

    def test_rejects_topic_owned_by_another_user(
        self, logged_in_client, other_user, db, app
    ):
        """User must not be able to create notes in another user's topic."""
        with app.app_context():
            from app.models import Topic
            other_topic = Topic(name="Someone else's topic", user_id=other_user.id)
            db.session.add(other_topic)
            db.session.commit()
            other_topic_id = other_topic.id

        payload = {
            "title": "Injecting a note",
            "content": "Content",
            "topic_id": other_topic_id,
        }
        response = logged_in_client.post(
            "/api/notes", data=json.dumps(payload), content_type="application/json"
        )
        assert response.status_code in (400, 403, 404), (
            "Should not allow creating notes in another user's topic"
        )

    def test_ai_note_with_source_conversation(self, logged_in_client, test_topic, db, app):
        """AI notes may include the source_conversation_id for traceability."""
        from app.models import Conversation
        with app.app_context():
            conv = Conversation(user_id=_get_user_id_from_session(logged_in_client, app))
            if conv.user_id is None:
                pytest.skip("Could not resolve user_id from session – check conftest.py")
            db.session.add(conv)
            db.session.commit()
            conv_id = conv.id

        payload = {
            "title": "AI Note with Source",
            "content": "Content from conversation",
            "topic_id": test_topic.id,
            "is_ai_generated": True,
            "source_conversation_id": conv_id,
        }
        response = logged_in_client.post(
            "/api/notes", data=json.dumps(payload), content_type="application/json"
        )
        # Endpoint should accept extra field gracefully (not 400) and save the note
        assert response.status_code in (200, 201)


# ---------------------------------------------------------------------------
# PATCH /api/notes/<id>  – update title or content of an existing note
# ---------------------------------------------------------------------------

class TestUpdateNoteEndpoint:
    """PATCH /api/notes/<id>"""

    def test_update_title(self, logged_in_client, test_note, db, app):
        response = logged_in_client.patch(
            f"/api/notes/{test_note.id}",
            data=json.dumps({"title": "Updated Title"}),
            content_type="application/json",
        )
        assert response.status_code == 200
        data = json.loads(response.data)
        assert data["title"] == "Updated Title"

    def test_update_content(self, logged_in_client, test_note, db, app):
        response = logged_in_client.patch(
            f"/api/notes/{test_note.id}",
            data=json.dumps({"content": "New content body"}),
            content_type="application/json",
        )
        assert response.status_code == 200
        data = json.loads(response.data)
        assert data["content"] == "New content body"

    def test_requires_authentication(self, client, test_note):
        response = client.patch(
            f"/api/notes/{test_note.id}",
            data=json.dumps({"title": "X"}),
            content_type="application/json",
        )
        assert response.status_code in (401, 302)

    def test_cannot_update_another_users_note(
        self, logged_in_client, other_user, db, app
    ):
        from app.models import Note
        with app.app_context():
            t = _make_topic(db, other_user.id)
            note = Note(
                title="Private", content="Private", is_ai_generated=False,
                user_id=other_user.id, topic_id=t.id
            )
            db.session.add(note)
            db.session.commit()
            private_id = note.id

        response = logged_in_client.patch(
            f"/api/notes/{private_id}",
            data=json.dumps({"title": "Hacked"}),
            content_type="application/json",
        )
        assert response.status_code in (403, 404)


# ---------------------------------------------------------------------------
# Left panel immediately reflects the newly-saved AI note
# ---------------------------------------------------------------------------

class TestAiNoteAppearsInLeftPanel:

    def test_ai_note_appears_in_documents_list(self, logged_in_client, test_topic, db, app):
        """After saving an AI note via POST /api/notes, it must appear in GET /api/documents."""
        payload = {
            "title": "Freshly Saved AI Note",
            "content": "AI-generated content",
            "topic_id": test_topic.id,
            "is_ai_generated": True,
        }
        post_resp = logged_in_client.post(
            "/api/notes", data=json.dumps(payload), content_type="application/json"
        )
        assert post_resp.status_code in (200, 201)
        saved_id = json.loads(post_resp.data)["id"]

        list_resp = logged_in_client.get("/api/documents")
        assert list_resp.status_code == 200
        docs = json.loads(list_resp.data)["documents"]
        doc_ids = [d["id"] for d in docs if d["type"] == "note"]
        assert saved_id in doc_ids, (
            "Newly saved AI note must immediately appear in /api/documents"
        )

    def test_ai_note_flagged_in_left_panel_list(self, logged_in_client, ai_note):
        """AI-generated notes should be marked so the UI can badge them differently."""
        response = logged_in_client.get("/api/notes")
        data = json.loads(response.data)
        ai_notes = [n for n in data["notes"] if n["id"] == ai_note.id]
        assert len(ai_notes) == 1
        assert ai_notes[0]["is_ai_generated"] is True


